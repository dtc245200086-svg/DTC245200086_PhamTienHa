\set ON_ERROR_STOP on

-- 1. TABLE: payment_idempotency_keys
-- Stores cryptographic request fingerprints and cached financial responses
-- to prevent duplicate payments, duplicate allocations, and double cash effects.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payment_idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(255) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    payment_id BIGINT REFERENCES public.payments(id) ON DELETE SET NULL,
    response_status INTEGER NOT NULL DEFAULT 201,
    response_body JSONB NOT NULL,
    created_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. CONSTRAINTS & INDEXES
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'payment_idempotency_keys_key_unique'
          AND conrelid = 'public.payment_idempotency_keys'::regclass
    ) THEN
        ALTER TABLE public.payment_idempotency_keys
        ADD CONSTRAINT payment_idempotency_keys_key_unique UNIQUE (idempotency_key);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS payment_idemp_key_idx
    ON public.payment_idempotency_keys (idempotency_key);

CREATE INDEX IF NOT EXISTS payment_idemp_pay_id_idx
    ON public.payment_idempotency_keys (payment_id);

CREATE INDEX IF NOT EXISTS payment_idemp_created_idx
    ON public.payment_idempotency_keys (created_at);

-- 3. PERMISSIONS / ROLE GRANTS
-- Least privilege security model:
--   - billing_app: full data access to payment_idempotency_keys
--   - billing_readonly: SELECT only
-- ----------------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE ON public.payment_idempotency_keys TO billing_app;
GRANT SELECT ON public.payment_idempotency_keys TO billing_readonly;

-- 4. VERIFICATION
-- ----------------------------------------------------------------------------
DO $$
DECLARE
    v_table_exists boolean;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'payment_idempotency_keys'
    ) INTO v_table_exists;

    IF NOT v_table_exists THEN
        RAISE EXCEPTION 'MIGRATION FAILED: payment_idempotency_keys was not created.';
    END IF;

    RAISE NOTICE 'MIGRATION 04 (P1.2.1 PAYMENT IDEMPOTENCY) APPLIED SUCCESSFULLY.';
END $$;
