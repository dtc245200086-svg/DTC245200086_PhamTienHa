-- 1. EXTEND EXISTING TABLES
ALTER TABLE public.customers
    ADD COLUMN IF NOT EXISTS code varchar(32),
    ADD COLUMN IF NOT EXISTS contact_person varchar(200),
    ADD COLUMN IF NOT EXISTS segment varchar(32) DEFAULT 'SME',
    ADD COLUMN IF NOT EXISTS credit_limit numeric(14, 2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS payment_term_id bigint,
    ADD COLUMN IF NOT EXISTS status varchar(24) DEFAULT 'ACTIVE';

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'customers_segment_check') THEN
        ALTER TABLE public.customers ADD CONSTRAINT customers_segment_check CHECK (segment IN ('Enterprise', 'SME', 'FDI'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'customers_credit_limit_check') THEN
        ALTER TABLE public.customers ADD CONSTRAINT customers_credit_limit_check CHECK (credit_limit >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'customers_status_check') THEN
        ALTER TABLE public.customers ADD CONSTRAINT customers_status_check CHECK (status IN ('ACTIVE', 'WARNING', 'LOCKED'));
    END IF;
END $$;

ALTER TABLE public.invoices
    ADD COLUMN IF NOT EXISTS e_invoice_code varchar(64),
    ADD COLUMN IF NOT EXISTS payment_term_id bigint,
    ADD COLUMN IF NOT EXISTS notes text;

ALTER TABLE public.invoice_items
    ADD COLUMN IF NOT EXISTS sku varchar(64),
    ADD COLUMN IF NOT EXISTS unit varchar(32) DEFAULT 'Đơn vị',
    ADD COLUMN IF NOT EXISTS discount_percent numeric(5, 2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS vat_rate numeric(5, 4) DEFAULT 0.10;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'invoice_items_discount_check') THEN
        ALTER TABLE public.invoice_items ADD CONSTRAINT invoice_items_discount_check CHECK (discount_percent BETWEEN 0 AND 100);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'invoice_items_vat_rate_check') THEN
        ALTER TABLE public.invoice_items ADD CONSTRAINT invoice_items_vat_rate_check CHECK (vat_rate BETWEEN 0 AND 0.20);
    END IF;
END $$;

ALTER TABLE public.payments
    ADD COLUMN IF NOT EXISTS bank_name varchar(100),
    ADD COLUMN IF NOT EXISTS bank_account varchar(50),
    ADD COLUMN IF NOT EXISTS notes text;


-- 2. PAYMENT TERMS (Net 15, Net 30, Net 60, Immediate, Installment)
CREATE TABLE IF NOT EXISTS public.payment_terms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    days integer NOT NULL CHECK (days >= 0),
    grace_period_days integer NOT NULL DEFAULT 0 CHECK (grace_period_days >= 0),
    late_penalty_rate numeric(5, 2) NOT NULL DEFAULT 0 CHECK (late_penalty_rate >= 0),
    early_discount_percent numeric(5, 2) NOT NULL DEFAULT 0 CHECK (early_discount_percent >= 0),
    early_discount_days integer NOT NULL DEFAULT 0 CHECK (early_discount_days >= 0),
    description text,
    is_default boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_customers_payment_term') THEN
        ALTER TABLE public.customers
            ADD CONSTRAINT fk_customers_payment_term
            FOREIGN KEY (payment_term_id) REFERENCES public.payment_terms(id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_invoices_payment_term') THEN
        ALTER TABLE public.invoices
            ADD CONSTRAINT fk_invoices_payment_term
            FOREIGN KEY (payment_term_id) REFERENCES public.payment_terms(id) ON DELETE SET NULL;
    END IF;
END $$;


-- 3. PRODUCTS & SERVICES MASTER CATALOG
CREATE TABLE IF NOT EXISTS public.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(64) NOT NULL UNIQUE,
    name varchar(255) NOT NULL CHECK (length(btrim(name)) > 0),
    category varchar(64) NOT NULL,
    unit varchar(32) NOT NULL,
    unit_price numeric(14, 2) NOT NULL CHECK (unit_price >= 0),
    vat_rate numeric(5, 4) NOT NULL DEFAULT 0.10 CHECK (vat_rate BETWEEN 0 AND 0.20),
    description text,
    status varchar(24) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISCONTINUED')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS products_sku_idx ON public.products(sku);
CREATE INDEX IF NOT EXISTS products_category_idx ON public.products(category);


-- 4. PAYMENT ALLOCATIONS (Multi-invoice payment distribution)
CREATE TABLE IF NOT EXISTS public.payment_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id bigint NOT NULL REFERENCES public.payments(id) ON DELETE CASCADE,
    invoice_id bigint NOT NULL REFERENCES public.invoices(id) ON DELETE RESTRICT,
    allocated_amount numeric(14, 2) NOT NULL CHECK (allocated_amount > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS payment_allocations_payment_idx ON public.payment_allocations(payment_id);
CREATE INDEX IF NOT EXISTS payment_allocations_invoice_idx ON public.payment_allocations(invoice_id);


-- 5. INVOICE ADJUSTMENTS (Credit Notes, Refunds, Discounts, Service Return)
CREATE SEQUENCE IF NOT EXISTS public.adjustment_no_seq AS bigint START WITH 1 INCREMENT BY 1 NO CYCLE;

CREATE TABLE IF NOT EXISTS public.invoice_adjustments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_no varchar(32) UNIQUE,
    original_invoice_id bigint NOT NULL REFERENCES public.invoices(id) ON DELETE RESTRICT,
    adjustment_type varchar(32) NOT NULL CHECK (adjustment_type IN ('DISCOUNT', 'DECREASE_AMOUNT', 'SERVICE_RETURN', 'INFO_CORRECTION')),
    amount numeric(14, 2) NOT NULL CHECK (amount >= 0),
    vat_rate numeric(5, 4) NOT NULL DEFAULT 0 CHECK (vat_rate BETWEEN 0 AND 0.20),
    vat_amount numeric(14, 2) NOT NULL DEFAULT 0 CHECK (vat_amount >= 0),
    total_amount numeric(14, 2) NOT NULL CHECK (total_amount >= 0),
    reason text NOT NULL CHECK (length(btrim(reason)) > 0),
    status varchar(24) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'APPROVED', 'PROCESSED')),
    notes text,
    created_by bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    approved_by bigint REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    approved_at timestamptz
);

CREATE INDEX IF NOT EXISTS invoice_adjustments_invoice_idx ON public.invoice_adjustments(original_invoice_id);
CREATE INDEX IF NOT EXISTS invoice_adjustments_status_idx ON public.invoice_adjustments(status);


-- 6. RECURRING PLANS (Subscription Billing Engine)
CREATE SEQUENCE IF NOT EXISTS public.recurring_plan_no_seq AS bigint START WITH 1 INCREMENT BY 1 NO CYCLE;

CREATE TABLE IF NOT EXISTS public.recurring_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL UNIQUE,
    customer_id bigint NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
    service_title varchar(255) NOT NULL CHECK (length(btrim(service_title)) > 0),
    contract_ref varchar(64),
    frequency varchar(24) NOT NULL CHECK (frequency IN ('Hàng tháng', 'Hàng quý', 'Hàng năm')),
    amount_per_period numeric(14, 2) NOT NULL CHECK (amount_per_period > 0),
    next_run_date date NOT NULL,
    completed_cycles integer NOT NULL DEFAULT 0 CHECK (completed_cycles >= 0),
    total_cycles integer CHECK (total_cycles IS NULL OR total_cycles >= completed_cycles),
    status varchar(24) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'PAUSED', 'FAILED', 'COMPLETED')),
    auto_sign boolean NOT NULL DEFAULT false,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS recurring_plans_customer_idx ON public.recurring_plans(customer_id);
CREATE INDEX IF NOT EXISTS recurring_plans_next_run_idx ON public.recurring_plans(next_run_date);
CREATE INDEX IF NOT EXISTS recurring_plans_status_idx ON public.recurring_plans(status);


-- 7. BANK TRANSACTIONS (Statement Matching & Reconciliation)
CREATE TABLE IF NOT EXISTS public.bank_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_date date NOT NULL,
    tx_time time NOT NULL DEFAULT '00:00:00',
    description text NOT NULL,
    amount numeric(14, 2) NOT NULL CHECK (amount > 0),
    tx_type varchar(12) NOT NULL CHECK (tx_type IN ('CREDIT', 'DEBIT')),
    reference varchar(120),
    bank_name varchar(100) NOT NULL,
    bank_account varchar(50) NOT NULL,
    status varchar(24) NOT NULL DEFAULT 'UNMATCHED' CHECK (status IN ('UNMATCHED', 'MATCHED', 'DISCREPANCY')),
    matched_invoice_id bigint REFERENCES public.invoices(id) ON DELETE SET NULL,
    matched_payment_id bigint REFERENCES public.payments(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS bank_tx_date_idx ON public.bank_transactions(tx_date);
CREATE INDEX IF NOT EXISTS bank_tx_status_idx ON public.bank_transactions(status);


-- 8. BUSINESS AUDIT LOGS (Append-only Financial Audit Trail)
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp timestamptz NOT NULL DEFAULT now(),
    actor_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
    actor_name varchar(100),
    actor_role varchar(32),
    ip_address varchar(64),
    module varchar(64) NOT NULL,
    action varchar(64) NOT NULL,
    target_ref varchar(100),
    severity varchar(16) NOT NULL DEFAULT 'INFO' CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    summary text NOT NULL,
    metadata jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_logs_timestamp_idx ON public.audit_logs(timestamp DESC);
CREATE INDEX IF NOT EXISTS audit_logs_module_idx ON public.audit_logs(module);
CREATE INDEX IF NOT EXISTS audit_logs_action_idx ON public.audit_logs(action);


-- 9. RBAC ROLES & PERMISSIONS
CREATE TABLE IF NOT EXISTS public.roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL UNIQUE,
    title varchar(100) NOT NULL,
    description text,
    is_system boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    module varchar(64) NOT NULL,
    description text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.role_permissions (
    role_id bigint NOT NULL REFERENCES public.roles(id) ON DELETE CASCADE,
    permission_id bigint NOT NULL REFERENCES public.permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);


